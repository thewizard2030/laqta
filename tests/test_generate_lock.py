"""The dependency locks must stay coherent with the profiles they claim to pin.

A lock that silently keeps an old set while a profile gains a requirement is
worse than no lock: it looks reproducible and is not. ``--verify`` is the
offline gate that catches exactly that, and these tests prove it catches it
rather than merely returning zero.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "scripts" / "generate_lock.py"


def _load_module():
    """Import scripts/generate_lock.py without making `scripts` a package."""
    spec = importlib.util.spec_from_file_location("generate_lock", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["generate_lock"] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture()
def lock_module():
    return _load_module()


@pytest.fixture()
def sandbox(tmp_path, lock_module, monkeypatch):
    """A throwaway repository tree with the same layout the script expects."""
    (tmp_path / "backend").mkdir()

    def write(name: str, content: str) -> Path:
        path = tmp_path / "backend" / name
        path.write_text(content, encoding="utf-8")
        return path

    write("requirements-asr.txt", "faster-whisper>=1.1\n")
    write("requirements-url.txt", "yt-dlp>=2024.04\n")
    write("requirements-analysis.txt", "scenedetect>=0.6\n")
    write(
        "requirements-all.txt",
        "-r requirements-asr.txt\n-r requirements-url.txt\n-r requirements-analysis.txt\n",
    )
    write(
        "requirements-lock.txt",
        "# Generated by scripts/generate_lock.py from backend/requirements-asr.txt\n"
        "faster-whisper==1.2.1 \\\n    --hash=sha256:aaaa\n",
    )
    write(
        "requirements-url-lock.txt",
        "# Generated by scripts/generate_lock.py from backend/requirements-url.txt\n"
        "yt-dlp==2026.10.26 \\\n    --hash=sha256:bbbb\n",
    )
    write(
        "requirements-analysis-lock.txt",
        "# Generated by scripts/generate_lock.py from backend/requirements-analysis.txt\n"
        "scenedetect==0.7.3 \\\n    --hash=sha256:cccc\n",
    )

    monkeypatch.setattr(lock_module, "REPO_ROOT", tmp_path)
    monkeypatch.setattr(
        lock_module,
        "PROFILES",
        {
            "default": ("backend/requirements-asr.txt", "backend/requirements-lock.txt"),
            "url": ("backend/requirements-url.txt", "backend/requirements-url-lock.txt"),
            "analysis": (
                "backend/requirements-analysis.txt",
                "backend/requirements-analysis-lock.txt",
            ),
            "all": ("backend/requirements-all.txt", None),
        },
    )
    return tmp_path


def test_a_coherent_tree_passes(sandbox, lock_module) -> None:
    assert lock_module.verify_locks() == []


def test_a_requirement_missing_from_its_lock_is_caught(sandbox, lock_module) -> None:
    """The exact failure the gate exists for: profile changed, lock did not."""
    (sandbox / "backend" / "requirements-analysis.txt").write_text(
        "scenedetect>=0.6\nlibrosa>=0.10\n", encoding="utf-8"
    )

    problems = lock_module.verify_locks()

    assert any("librosa" in problem for problem in problems), problems


def test_a_missing_lock_file_is_caught(sandbox, lock_module) -> None:
    (sandbox / "backend" / "requirements-url-lock.txt").unlink()

    problems = lock_module.verify_locks()

    assert any("requirements-url-lock.txt" in problem for problem in problems)


def test_a_package_without_a_hash_is_caught(sandbox, lock_module) -> None:
    """`--require-hashes` would refuse the install, so the lock is not a lock."""
    (sandbox / "backend" / "requirements-url-lock.txt").write_text(
        "# Generated by scripts/generate_lock.py from backend/requirements-url.txt\n"
        "yt-dlp==2026.10.26\n",
        encoding="utf-8",
    )

    problems = lock_module.verify_locks()

    assert any("no hash" in problem for problem in problems), problems


def test_a_lock_generated_from_another_profile_is_caught(sandbox, lock_module) -> None:
    (sandbox / "backend" / "requirements-url-lock.txt").write_text(
        "# Generated by scripts/generate_lock.py from backend/requirements-asr.txt\n"
        "yt-dlp==2026.10.26 \\\n    --hash=sha256:bbbb\n",
        encoding="utf-8",
    )

    problems = lock_module.verify_locks()

    assert any("does not name" in problem for problem in problems), problems


def test_a_duplicate_pin_is_caught(sandbox, lock_module) -> None:
    (sandbox / "backend" / "requirements-url-lock.txt").write_text(
        "# Generated by scripts/generate_lock.py from backend/requirements-url.txt\n"
        "yt-dlp==2026.10.26 \\\n    --hash=sha256:bbbb\n"
        "yt-dlp==2026.10.26 \\\n    --hash=sha256:bbbb\n",
        encoding="utf-8",
    )

    problems = lock_module.verify_locks()

    assert any("pinned twice" in problem for problem in problems), problems


def test_the_composed_profile_must_include_every_capability(sandbox, lock_module) -> None:
    (sandbox / "backend" / "requirements-all.txt").write_text(
        "-r requirements-asr.txt\n", encoding="utf-8"
    )

    problems = lock_module.verify_locks()

    assert any("requirements-url.txt" in problem for problem in problems), problems


def test_name_normalisation_matches_the_lock(lock_module) -> None:
    assert lock_module._normalise("OpenCV_Python") == "opencv-python"
    assert lock_module._normalise("faster_whisper") == "faster-whisper"
    assert lock_module._normalise("yt.dlp") == "yt-dlp"


