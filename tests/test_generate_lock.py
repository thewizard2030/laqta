def test_the_shipped_repository_is_coherent() -> None:
    """The gate must pass on the tree as committed, not only on fixtures."""
    assert _load_module().verify_locks() == []


def test_the_analysis_profile_has_exactly_one_cv2_provider() -> None:
    """Two packages providing `cv2` silently shadow each other."""
    lock = (REPO_ROOT / "backend" / "requirements-analysis-lock.txt").read_text(encoding="utf-8")

    providers = [
        line.split("==")[0]
        for line in lock.splitlines()
        if line.startswith(("opencv-python==", "opencv-contrib-python=="))
    ]

    assert providers == ["opencv-python"], providers


def test_every_locked_profile_ships_a_lock_file() -> None:
    module = _load_module()
    for name, (requirements_rel, output_rel) in module.PROFILES.items():
        if output_rel is None:
            continue
        assert (REPO_ROOT / requirements_rel).is_file(), name
        assert (REPO_ROOT / output_rel).is_file(), name
