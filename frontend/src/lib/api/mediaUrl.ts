/**
 * URL for the local media file stream used by <video> source previews
 * (backend GET /api/media/{mediaId}/file, byte-range seeks supported).
 *
 * Files remain local: the browser fetches them from the same 127.0.0.1
 * backend that serves the API. Returns null only in non-browser contexts
 * (e.g. SSR), where playback is not supported.
 */

export function generateMediaFileUrl(mediaId: string): string | null {
  if (typeof window === "undefined") {
    return null;
  }
  return `/api/media/${encodeURIComponent(mediaId)}/file`;
}

/**
 * URL for a candidate clip's real preview frame (backend GET
 * /api/media/{mediaId}/candidates/{candidateId}/thumbnail).
 *
 * Frames are generated by the `candidate_thumbnails` background job after
 * clip generation; until then the route answers 404 and callers must show
 * an honest placeholder instead of a fake screenshot.
 */
export function generateCandidateThumbnailUrl(mediaId: string, candidateId: string): string | null {
  if (typeof window === "undefined") {
    return null;
  }
  return `/api/media/${encodeURIComponent(mediaId)}/candidates/${encodeURIComponent(
    candidateId,
  )}/thumbnail`;
}
